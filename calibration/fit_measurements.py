#!/usr/bin/env python3
"""Reproduce the coefficients from the recorded OLED and reference readings.

No third party dependencies. Run from any directory; writes the shared header
and a numerical audit beside the source measurements.
"""
import json
import math
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent


def fit(xs, ys):
    n = len(xs[0])
    a = [[sum(x[i] * x[j] for x in xs) for j in range(n)] +
         [sum(x[i] * y for x, y in zip(xs, ys))] for i in range(n)]
    for i in range(n):
        pivot = max(range(i, n), key=lambda j: abs(a[j][i]))
        a[i], a[pivot] = a[pivot], a[i]
        divisor = a[i][i]
        if abs(divisor) < 1e-12:
            raise ValueError("Singular calibration data")
        a[i] = [v / divisor for v in a[i]]
        for j in range(n):
            if j != i:
                factor = a[j][i]
                a[j] = [v - factor * w for v, w in zip(a[j], a[i])]
    # Match the values actually emitted to the C header.
    return [round(a[i][-1], 9) for i in range(n)]


def metrics(errors):
    return {"samples": len(errors), "mae": sum(map(abs, errors)) / len(errors),
            "max_abs": max(map(abs, errors)),
            "rmse": math.sqrt(sum(e * e for e in errors) / len(errors))}


def calculate():
    data = json.loads((HERE / "measurements_2026-10-25.json").read_text())
    rows = data["rows"]
    currents = {}
    for name, measured, reference in (("iin", 10, 3), ("iout", 11, 6)):
        xs = [float(r[measured]) for r in rows]
        ys = [float(r[reference]) for r in rows]
        coeff = fit([[x*x, x, 1] for x in xs], ys)
        q, k, b = coeff
        currents[name] = {"coefficients_q_k_b": coeff, "upper_nominal_a": max(xs),
                          "before": metrics([x-y for x, y in zip(xs, ys)]),
                          "after": metrics([max(0, q*x*x+k*x+b)-y for x, y in zip(xs, ys)])}
    q, k, b = currents["iout"]["coefficients_q_k_b"]
    valid = [r for r in rows if r[0] not in data["exclude_vout_ids"]]
    xs = [[float(r[9]), max(0, q*float(r[11])**2+k*float(r[11])+b), 1] for r in valid]
    ys = [float(r[5]) for r in valid]
    coeff = fit(xs, ys)
    result = {"currents": currents,
              "vout": {"coefficients_voltage_current_offset": coeff,
                       "excluded_ids": data["exclude_vout_ids"],
                       "before": metrics([x[0]-y for x, y in zip(xs, ys)]),
                       "after": metrics([sum(c*v for c, v in zip(coeff, x))-y for x, y in zip(xs, ys)])},
              "vin": "No ADC calibration: reference is before D4, ADC is after D4.",
              "scope": "In-sample residuals from rounded OLED readings; not independent hardware accuracy."}
    return result


def header(result):
    defines = []
    for name in ("iin", "iout"):
        vals = result["currents"][name]
        for suffix, value in zip(("Q", "K", "B"), vals["coefficients_q_k_b"]):
            defines.append(f"#define CAL_{name.upper()}_{suffix} {value:.9f}f")
        defines.append(f"#define CAL_{name.upper()}_UPPER_A {vals['upper_nominal_a']:.9f}f")
    for suffix, value in zip(("K", "CURRENT_V_PER_A", "OFFSET_V"), result["vout"]["coefficients_voltage_current_offset"]):
        defines.append(f"#define CAL_VOUT_{suffix} {value:.9f}f")
    return '''/* Generated by calibration/fit_measurements.py from measured data, 2026-10-25.
 * Nominal values reproduce V2.05: voltage = pin V * 7, current = pin V * 1 A/V.
 * VIN remains the actual D4-downstream sample; no fictitious diode correction.
 */
#ifndef MEASUREMENT_CALIBRATION_H
#define MEASUREMENT_CALIBRATION_H

#define CAL_VIN_ADC_SCALE 7.0f
#define CAL_VOUT_ADC_SCALE 7.0f
#define CAL_IIN_BASE_A_PER_V 1.0f
#define CAL_IOUT_BASE_A_PER_V 1.0f
''' + '\n'.join(defines) + '''

/* Above the measured range use its positive tangent, never cap a fault current.
 * This preserves a monotonic OCP signal without claiming calibrated accuracy
 * outside the measured range. The zero floor preserves unidirectional sensing.
 */
static inline float Cal_Current(float x, float q, float k, float b, float upper)
{
    float y;
    if (x <= 0.0f) return 0.0f;
    if (x > upper)
        y = (q * upper + k) * upper + b + (2.0f*q*upper + k)*(x-upper);
    else
        y = (q * x + k) * x + b;
    return (y > 0.0f) ? y : 0.0f;
}

static inline float Cal_Iin(float pin_v)
{
    return Cal_Current(pin_v * CAL_IIN_BASE_A_PER_V,
                       CAL_IIN_Q, CAL_IIN_K, CAL_IIN_B, CAL_IIN_UPPER_A);
}

static inline float Cal_Iout(float pin_v)
{
    return Cal_Current(pin_v * CAL_IOUT_BASE_A_PER_V,
                       CAL_IOUT_Q, CAL_IOUT_K, CAL_IOUT_B, CAL_IOUT_UPPER_A);
}

/* Current-dependent terminal-voltage estimate, not an extra ADC measurement.
 * Keep the nominal PA6 reading separately and refresh on either channel group.
 */
static inline float Cal_Vout(float nominal_v, float calibrated_iout)
{
    float v = nominal_v * CAL_VOUT_K + calibrated_iout * CAL_VOUT_CURRENT_V_PER_A
              + CAL_VOUT_OFFSET_V;
    return (nominal_v > 0.0f && v > 0.0f) ? v : 0.0f;
}
#endif
'''


if __name__ == "__main__":
    result = calculate()
    (ROOT / "Core/Inc/measurement_calibration.h").write_text(header(result))
    (HERE / "fit_results.json").write_text(json.dumps(result, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps(result, ensure_ascii=False, indent=2))
