#!/usr/bin/env python3
"""Reproduce V2.08 voltage calibration from both pages of the V2 measurements.

Standard library only. Page 2 is fitted before page 1. The latter contains
V2.06/V2.07 display readings, so its residual is applied after that conversion.
"""
import json
from pathlib import Path

from fit_measurements import fit, metrics

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent


def corrected_rows(data, page):
    sheet = data["pages"][page - 1]
    rows = [list(row) for row in sheet["rows"]]
    for change in data["corrections"]:
        if change["page"] == page:
            index = sheet["columns"].index(change["column"])
            row = next(r for r in rows if int(r[0]) == change["test_id"])
            if row[index] != change["original"]:
                raise ValueError("Correction does not match the preserved source")
            row[index] = change["corrected"]
    return rows


def calculate():
    data = json.loads((HERE / "measurements_2026-10-27.json").read_text())
    rows = corrected_rows(data, 2)
    groups = []
    for current in sorted({float(r[4]) for r in rows}):
        group = [r for r in rows if float(r[4]) == current]
        k, b = fit([[float(r[1]), 1] for r in group],
                   [float(r[3]) for r in group])
        groups.append({"current_a": current, "k": k, "b_v": b})
    ki, k0 = fit([[g["current_a"], 1] for g in groups], [g["k"] for g in groups])
    bi, b0 = fit([[g["current_a"], 1] for g in groups], [g["b_v"] for g in groups])

    def forward(command, current):
        return (ki * current + k0) * command + bi * current + b0

    errors, quantized_errors = [], []
    for r in rows:
        command, actual, current = float(r[1]), float(r[3]), float(r[4])
        errors.append(forward(command, current) - actual)
        # Correct the original setpoint, quantize, and replay the locally
        # measured anchor with the fitted slope. Retain the sample residual;
        # forward(inverse(actual)) would merely test an algebraic identity.
        k = ki * current + k0
        inverse = (command - bi * current - b0) / k
        dac = (17.07091 - inverse) / 4.545455
        code = int(dac * 4095 / 3.3 + 0.5)
        reconstructed = 17.07091 - 4.545455 * code * 3.3 / 4095
        quantized_errors.append(actual + k * (reconstructed - command) - command)
    dac = {
        "first_pass": groups,
        "second_pass": {"k_current": ki, "k_offset": k0,
                        "b_current": bi, "b_offset_v": b0},
        "command_range_v": [min(float(r[1]) for r in rows), max(float(r[1]) for r in rows)],
        "current_range_a": [min(float(r[4]) for r in rows), max(float(r[4]) for r in rows)],
        "before": metrics([float(r[3]) - float(r[1]) for r in rows]),
        "forward_residual": metrics(errors),
        "inverse_with_12bit_dac_residual": metrics(quantized_errors),
        "extension": "Outside 5..9 V, hold the calibration increment at the voltage boundary; current is bounded to 0..2 A, with 0..0.5 A extrapolated.",
    }

    rows = corrected_rows(data, 1)
    # Only a narrow load sweep at one setpoint exists. Preserve the old voltage
    # gain and fit its remaining error versus already-calibrated OLED current.
    ci, cb = fit([[float(r[11]), 1] for r in rows],
                 [float(r[5]) - float(r[9]) for r in rows])
    adc = {
        "residual_current_v_per_a": ci, "residual_offset_v": cb,
        "before": metrics([float(r[9]) - float(r[5]) for r in rows]),
        "after": metrics([float(r[9]) + ci * float(r[11]) + cb - float(r[5]) for r in rows]),
        "reference_range_v": [min(float(r[5]) for r in rows), max(float(r[5]) for r in rows)],
        "current_range_a": [min(float(r[11]) for r in rows), max(float(r[11]) for r in rows)],
        "reason": "Single-setpoint load sweep does not identify independent voltage gain and current drop; retain the V2.06 voltage gain and trim the residual.",
    }
    return {"version": "V2.08", "dac": dac, "adc": adc,
            "corrections": data["corrections"],
            "scope": "In-sample/model residuals from rounded readings, not post-flash hardware accuracy. Second-page data describe terminal output, not measured PA4 voltage."}


def header(result):
    d, a = result["dac"]["second_pass"], result["adc"]
    return f'''/* Generated by calibration/fit_voltage_v2.py, 2026-10-27 (V2.08).
 * Page 2: two-pass terminal-output model. Page 1: V2.06/V2.07 ADC trim.
 * These data do not independently calibrate the physical PA4 pin voltage.
 */
#ifndef VOLTAGE_CALIBRATION_H
#define VOLTAGE_CALIBRATION_H

#define CAL_DAC_BASE_A 17.07091f
#define CAL_DAC_BASE_B 4.545455f
#define CAL_DAC_K_I {d['k_current']:.9f}f
#define CAL_DAC_K_0 {d['k_offset']:.9f}f
#define CAL_DAC_B_I {d['b_current']:.9f}f
#define CAL_DAC_B_0 {d['b_offset_v']:.9f}f
#define CAL_VOUT_TRIM_I {a['residual_current_v_per_a']:.9f}f
#define CAL_VOUT_TRIM_B {a['residual_offset_v']:.9f}f

/* Invert the terminal model. Hold the correction increment at the measured
 * voltage boundary beyond 5..9 V, rather than extrapolating its voltage gain.
 * Below 0.5 A the current model is extrapolated to zero; above 2 A hold it.
 * Physical DAC limits and non-finite checks remain in the caller.
 */
static inline float Cal_TargetToDac(float target_v, float iout)
{{
    float current = iout < 0.0f ? 0.0f : (iout > 2.0f ? 2.0f : iout);
    float v = target_v < 5.0f ? 5.0f : (target_v > 9.0f ? 9.0f : target_v);
    float k = CAL_DAC_K_I * current + CAL_DAC_K_0;
    float b = CAL_DAC_B_I * current + CAL_DAC_B_0;
    float command = target_v + (v - b) / k - v;
    return (CAL_DAC_BASE_A - command) / CAL_DAC_BASE_B;
}}
#endif
'''


if __name__ == "__main__":
    result = calculate()
    (ROOT / "Core/Inc/voltage_calibration.h").write_text(header(result))
    (HERE / "voltage_fit_results_2026-10-27.json").write_text(
        json.dumps(result, ensure_ascii=False, indent=2) + "\n")
    print(json.dumps(result, ensure_ascii=False, indent=2))
